import test from 'node:test';
import assert from 'node:assert/strict';
import express from 'express';
import mongoose from 'mongoose';
import { mkdtemp, mkdir, writeFile, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';

test('checkpoint auth, baseline guard, cascades, exact restore and verification', { skip: !process.env.RGBD_TEST_MONGO }, async () => {
  assert.match(process.env.RGBD_TEST_MONGO, /\/vision_rgbd_sync_test$/);
  const root = await mkdtemp(path.join(tmpdir(), 'vision-maintenance-'));
  process.env.API_TEST_CHECKPOINT_ROOT = path.join(root, 'checkpoints');
  process.env.VIDEO_ARCHIVE_ROOT = path.join(root, 'video');
  process.env.RGBD_ARCHIVE_ROOT = path.join(root, 'video/rgbd');
  process.env.MQTT_URL = 'mqtt://127.0.0.1:1';
  process.env.API_TEST_ADMIN_TOKEN = 'local-isolated-test-token-0123456789';
  process.env.API_TEST_ENABLED = '1';
  const { default: routes } = await import('../src/routes/testingRoutes.js');
  const { guard, lease: initialLease } = await import('../src/maintenance/lease.js');
  assert.equal(initialLease, null);
  const { backendInstanceId } = await import('../src/runtimeIdentity.js');
  const { default: User } = await import('../src/models/User.js');
  const { default: Operation } = await import('../src/models/Operation.js');
  const { default: Detection } = await import('../src/models/Detection.js');
  const { default: Camera } = await import('../src/models/CameraExtrinsics.js');
  const { descendants, deleteUser, deleteDetection } = await import('../src/maintenance/cascade.js');
  const { persistDetectionWithScrewFusion } = await import('../src/positioning/screwFusion.js');
  const { getSimulationConfigValue, setSimulationConfigValue } = await import('../src/controllers/simulationController.js');
  const app = express(); app.use(express.json()); app.use('/api', guard); app.use('/api/testing', routes);
  app.patch('/api/users/:id', (_req, res) => res.json({ ok: true }));
  app.get('/api/read', (_req, res) => res.json({ ok: true }));
  const server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
  const base = `http://127.0.0.1:${server.address().port}/api/`;
  const realFetch = globalThis.fetch;
  let aiLease = null, aiConfig = { detectionAlgorithm: 'mock_yolo', fusionAlgorithm: 'ekf', screwFusionAlgorithm: 'average' };
  const oldConfig = { ...getSimulationConfigValue() };
  globalThis.fetch = async (url, options = {}) => {
    if (!String(url).startsWith('http://127.0.0.1:8000/')) return realFetch(url, options);
    const body = options.body ? JSON.parse(options.body) : {};
    if (String(url).endsWith('/api/testing/lease')) {
      if (body.action === 'acquire') { aiLease = body.id; return Response.json({ config: { ...aiConfig } }); }
      assert.equal(body.id, aiLease);
      if (body.action === 'restore') aiConfig = body.config;
      if (body.action === 'release') aiLease = null;
      return Response.json({ status: 'success' });
    }
    return Response.json(aiConfig);
  };
  const auth = { Authorization: 'Bearer ' + process.env.API_TEST_ADMIN_TOKEN };
  let checkpoint, users = [], operations = [], originalCamera;
  const request = async (route, body, headers = auth, method = body === undefined ? 'GET' : 'POST') => {
    const response = await realFetch(base + route, { method, headers: { 'Content-Type': 'application/json', ...headers }, body: body === undefined ? undefined : JSON.stringify(body) });
    let value; try { value = await response.json(); } catch { value = null; }
    return { status: response.status, body: value };
  };
  await mongoose.connect(process.env.RGBD_TEST_MONGO);
  try {
    originalCamera = await Camera.collection.findOne({ key: 'default' });
    const email = `maintenance-${new mongoose.Types.ObjectId()}@example.com`;
    await mkdir(process.env.VIDEO_ARCHIVE_ROOT, { recursive: true });
    const baselineVideo = path.join(process.env.VIDEO_ARCHIVE_ROOT, 'existing.mp4');
    await writeFile(baselineVideo, 'original-video');
    const baseline = await User.create({ name: 'baseline', email, passwordHash: 'opaque' }); users.push(baseline._id);
    assert.equal((await request('testing/capabilities', undefined, {})).status, 401);
    process.env.API_TEST_ENABLED = '0'; assert.equal((await request('testing/capabilities')).status, 404); process.env.API_TEST_ENABLED = '1';
    const capabilities = await request('testing/capabilities'); assert.equal(capabilities.body.baselineGuard, true);
    assert.equal((await request('testing/checkpoints', { backendInstanceId: 'wrong' })).status, 409);
    const created = await request('testing/checkpoints', { backendInstanceId, clientRunId: 'isolated' });
    assert.equal(created.status, 201, JSON.stringify(created.body)); checkpoint = created.body.id;
    const leaseHeaders = { ...auth, 'X-API-Test-Checkpoint': checkpoint };
    assert.equal((await request('read', undefined, {})).status, 423);
    assert.equal((await request('read', undefined, leaseHeaders)).status, 200);
    assert.equal((await request(`users/${baseline.id}`, {}, leaseHeaders, 'PATCH')).status, 409);
    assert.equal((await request(`testing/checkpoints/${checkpoint}/cleanup`, { owned: { users: [baseline.id] } })).status, 409);
    const ownUser = await User.create({ name: 'new', email: 'new-' + email, passwordHash: 'opaque' }); users.push(ownUser._id);
    const operation = await Operation.create({ userId: ownUser._id, startTime: new Date(), endTime: new Date() }); operations.push(operation._id);
    const sample = { operationId: operation._id, timestamp: new Date(), objectClass: 'M4', screwId: 'M4-1', rawAbsolutePosition: { x: 1, y: 2, z: 1 }, absolutePosition: { x: 1, y: 2, z: 1 } };
    const detection = await persistDetectionWithScrewFusion(sample);
    const second = await persistDetectionWithScrewFusion({ ...sample, timestamp: new Date(Date.now() + 10), rawAbsolutePosition: { x: 1.1, y: 2, z: 1 } });
    await Operation.updateOne({ _id: operation._id }, { $unset: { endTime: '' } });
    await assert.rejects(deleteDetection(detection.id), /End operation/);
    await Operation.updateOne({ _id: operation._id }, { $set: { endTime: new Date() } });
    await descendants.find(model => model.modelName === 'RawSensorMeasurement').create({ operationId: operation._id, timestamp: new Date(), source: 'simulation', payload: { ranges: [] } });
    await descendants.find(model => model.modelName === 'OperatorTelemetry').create({ operationId: operation._id, timestamp: new Date(), fusionAlgorithm: 'ekf', telemetry: { position: { x: 1, y: 2, z: 1 } } });
    await descendants.find(model => model.modelName === 'RgbdFrame').create({ operationId: operation._id, sessionId: '00000000-0000-4000-8000-000000000001', frameId: 0, captureTimeNs: '1', receivedTimeNs: '2', processedTimeNs: '3', status: 'no_detection' });
    const owned = { users: [ownUser.id], operations: [operation.id], detections: [detection.id, second.id] };
    const prefix = `testing/checkpoints/${checkpoint}/`;
    const before = await request(prefix + 'inspect', { owned, root: { kind: 'detection', id: detection.id } });
    assert.equal(before.body.remaining, 5);
    await deleteDetection(detection.id);
    assert.equal((await request(prefix + 'inspect', { owned, root: { kind: 'detection', id: detection.id } })).body.remaining, 0);
    const screwModel = descendants.find(model => model.modelName === 'ScrewLocalizationTelemetry');
    assert.equal((await screwModel.findOne({ detectionId: second._id })).observationCount, 1);
    const folder = path.join(process.env.RGBD_ARCHIVE_ROOT, operation.id, 'session'); await mkdir(folder, { recursive: true });
    await writeFile(path.join(folder, '000000000000.rgbd'), 'test');
    const archive = path.join(process.env.VIDEO_ARCHIVE_ROOT, `color_detect_${operation.id}_123.mp4`); await writeFile(archive, 'test');
    assert((await request(prefix + 'inspect', { owned, root: { kind: 'user', id: ownUser.id } })).body.remaining > 2);
    await deleteUser(ownUser.id);
    assert.equal((await request(prefix + 'inspect', { owned, root: { kind: 'user', id: ownUser.id } })).body.remaining, 0);
    assert.equal(await readFile(baselineVideo, 'utf8'), 'original-video', 'original archive is never deleted');
    assert(await User.exists({ _id: baseline._id }));
    await Camera.collection.updateOne({ key: 'default' }, { $set: { translation: { x: 9, y: 9, z: 9 } } }, { upsert: true });
    setSimulationConfigValue({ fusionAlgorithm: 'gwo4d', screwFusionAlgorithm: 'rmv_fgo' }); aiConfig = { ...aiConfig, fusionAlgorithm: 'gwo4d' };
    assert.equal((await request(prefix + 'quiesce', { owned })).status, 200);
    assert.equal((await request('read', undefined, leaseHeaders)).status, 423);
    assert.equal((await request(prefix + 'cleanup', { owned })).body.remaining, 0);
    assert.equal((await request(prefix + 'restore', {})).status, 200);
    const verified = await request(prefix + 'verify', {});
    assert.equal(verified.status, 200);
    assert.equal(verified.body.originalDataUnchanged, true, JSON.stringify(verified.body));
    assert.equal(verified.body.settingsRestored, true);
    assert.equal(verified.body.writersIdle, true);
    assert.equal(verified.body.testDataRemaining, 0); assert.equal(verified.body.testFilesRemaining, 0);
    assert.equal((await request('read', undefined, {})).status, 200);
    assert.equal((await request('read', undefined, leaseHeaders)).status, 423, 'late checkpoint messages cannot resume after release');
    const ledger = await readFile(path.join(process.env.API_TEST_CHECKPOINT_ROOT, checkpoint + '.json'), 'utf8');
    assert(!ledger.includes(process.env.API_TEST_ADMIN_TOKEN)); assert(!ledger.includes('passwordHash'));
    // A second run exercises the other calibration branch: exact restoration
    // of an existing document, including its original _id and timestamps.
    if (!await Camera.exists({ key: 'default' })) await Camera.create({ key: 'default' });
    const cameraBefore = await Camera.collection.findOne({ key: 'default' });
    const secondCheckpoint = await request('testing/checkpoints', { backendInstanceId, clientRunId: 'existing-camera' });
    assert.equal(secondCheckpoint.status, 201);
    checkpoint = secondCheckpoint.body.id;
    const secondPrefix = `testing/checkpoints/${checkpoint}/`;
    const lostResponse = await User.create({ name: 'lost-response', email: 'lost-' + email, passwordHash: 'opaque' }); users.push(lostResponse._id);
    const recovery = { intents: [{ lookupEmail: lostResponse.email }] };
    await Camera.collection.updateOne({ key: 'default' }, { $set: { translation: { x: 99, y: 0, z: 0 }, updatedAt: new Date(Date.now() + 10000) } });
    await User.collection.updateOne({ _id: baseline._id }, { $set: { name: 'external-change' } });
    assert.equal((await request(secondPrefix + 'quiesce', recovery)).status, 200);
    assert.equal((await request(secondPrefix + 'cleanup', recovery)).body.remaining, 0);
    assert.equal(await User.exists({ _id: lostResponse._id }), null, 'exact email intent recovers a lost create response');
    assert.equal((await request(secondPrefix + 'restore', {})).status, 200);
    assert.deepEqual(await Camera.collection.findOne({ key: 'default' }), cameraBefore, 'native BSON restore retains timestamps and identity');
    const changed = await request(secondPrefix + 'verify', {});
    assert.equal(changed.body.originalDataUnchanged, false);
    assert(changed.body.differences.some(row => row.id === baseline.id && row.change === 'modified'));
    assert.equal((await request('read', undefined, {})).status, 423, 'verification failure keeps lease locked');
    assert.equal((await User.findById(baseline._id)).name, 'external-change', 'never overwrite original business data to conceal changes');
    await User.collection.updateOne({ _id: baseline._id }, { $set: { name: baseline.name } });
    assert.equal((await request(secondPrefix + 'verify', {})).body.originalDataUnchanged, true);
    checkpoint = null;
  } finally {
    globalThis.fetch = realFetch;
    const { saveLease } = await import('../src/maintenance/lease.js'); saveLease(null);
    setSimulationConfigValue(oldConfig);
    for (const model of descendants) await model.deleteMany({ operationId: { $in: operations } });
    await Operation.deleteMany({ _id: { $in: operations } }); await User.deleteMany({ _id: { $in: users } });
    if (originalCamera) await Camera.collection.replaceOne({ key: 'default' }, originalCamera, { upsert: true }); else await Camera.collection.deleteOne({ key: 'default' });
    const pipeline = await import('../src/mqtt/mqttClient.js'); pipeline.default.end(true);
    await mongoose.disconnect(); await new Promise(resolve => server.close(resolve));
    assert(root.startsWith(path.join(tmpdir(), 'vision-maintenance-'))); await rm(root, { recursive: true, force: true });
  }
});
